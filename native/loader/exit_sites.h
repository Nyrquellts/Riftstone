// DDDA build 2364871: the code that decides how the game closes (docs/runtime.md, "Why the game closed").
//
// WinMain (0x004079E0) builds sApp on its stack; sApp's constructor stores it at [0x018D0F50]. Its
// message loop (0x00DF0D20: PeekMessageA, TranslateMessage, DispatchMessageW, one frame) ends on WM_QUIT
// or when sApp+0x266C is set, and only the game's own exit sets that: the title screen's Exit Game
// (uGUITitle, 0x0072C440) and the quit prompt of the start-up save check (aBbsRpg, 0x00530AF0 state 8).
// WM_CLOSE on the main window asks sMain ([0x018D0B28]) whether it may close, then runs its exit request
// (0x00DBD0F0): sMain+0x34 = 1, SendMessageA(window, WM_DESTROY); WM_DESTROY posts WM_QUIT.
//
// fixes.cpp reads the two flags only after every site below holds these bytes; the stand-in game
// (test/harness.cpp, DDDA layout) lays the same bytes out at the same addresses.
