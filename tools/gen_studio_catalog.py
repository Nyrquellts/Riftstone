"""Write native/studio/src/catalog.inc and version.h: what Riftstone Studio (the exe) knows about the features, from the
toolkit's own tables, so the two never disagree.

    python tools/gen_studio_catalog.py           write them
    python tools/gen_studio_catalog.py --check   exit 1 unless the files are what this would write (the gate runs this)

From src/riftstone/plugins.py: CATALOG (each feature's title and line), _RULES and _SECTION_RULES (the checks a typed
value gets), _BOOL_KEYS (keys that are 0 or 1) and PANEL_KEYS (the in-game panel's named keys); from
src/riftstone/__init__.py the version; from package.py, legal.py and loader.py what the exe's mod pack carries
(Riftstone's own plugins, the licence, the notices) and the [d3d9] chain DXVK goes behind. The exe's validator is plugins._valid ported; native/studio/test/run_tests.py
compares the two on every rule.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from riftstone import __version__, legal, loader, package, plugins  # noqa: E402

OUT = ROOT / "native" / "studio" / "src" / "catalog.inc"
VERSION = OUT.with_name("version.h")
KINDS = ("int", "float", "auto_float", "auto_int", "int_or_zero", "float_or_zero", "shadow", "fkey", "choice")


def wide(text: str) -> str:
    """A C++ wide string literal; every character past ASCII as \\uXXXX, so the file is ASCII."""
    out = []
    for ch in text:
        if ch in '\\"':
            out.append("\\" + ch)
        elif ch in "\r\n\t":
            out.append({"\r": "\\r", "\n": "\\n", "\t": "\\t"}[ch])
        elif 0x20 <= ord(ch) < 0x7F:
            out.append(ch)
        elif ord(ch) <= 0xFFFF:
            out.append(f"\\u{ord(ch):04X}")
        else:
            out.append(f"\\U{ord(ch):08X}")
    return 'L"' + "".join(out) + '"'


def number(v) -> str:
    return repr(float(v))


def rule_row(stem: str, section: str, key: str | None, rule: tuple) -> str:
    kind = rule[0]
    if kind not in KINDS:
        raise SystemExit(f"plugins._RULES: {stem}/{section}/{key} has a kind the exe does not know: {kind}")
    lo = hi = "0.0"
    lo_text = hi_text = choices = 'L""'
    if kind == "choice":
        choices = wide("|".join(rule[1:]))
    elif kind != "fkey":
        # the bounds as numbers, and as plugins._valid's messages print them (10, not 10.0; 0.25 as 0.25)
        lo, hi, lo_text, hi_text = number(rule[1]), number(rule[2]), wide(str(rule[1])), wide(str(rule[2]))
    return (f"    {{{wide(stem)}, {wide(section)}, {wide(key) if key is not None else 'nullptr'}, "
            f"RULE_{kind.upper()}, {lo}, {hi}, {lo_text}, {hi_text}, {choices}}},")


def render() -> str:
    lines = [
        "// Generated by tools/gen_studio_catalog.py from src/riftstone/plugins.py.",
        "// Never hand-edit: change the toolkit's tables and run the tool (the gate runs it with --check).",
        "",
        "static const CatalogEntry kCatalog[] = {",
    ]
    for stem, info in plugins.CATALOG.items():
        lines.append(f"    {{{wide(stem)}, {wide(info['title'])}, {wide(info['summary'])}}},")
    lines += ["};", "", "static const Rule kRules[] = {"]
    for (stem, section, key), rule in plugins._RULES.items():
        lines.append(rule_row(stem, section, key, rule))
    lines += ["};", "", "static const Rule kSectionRules[] = {"]
    for (stem, section), rule in plugins._SECTION_RULES.items():
        lines.append(rule_row(stem, section, None, rule))
    lines += ["};", ""]
    m = re.fullmatch(r"\^\(([a-z_|]+)\)\$", plugins._BOOL_KEYS.pattern)
    if not m:
        raise SystemExit("plugins._BOOL_KEYS is no longer ^(a|b|...)$: teach this tool its new form")
    lines.append("static const wchar_t* const kBoolKeys[] = {")
    lines += [f"    {wide(k)}," for k in m.group(1).split("|")]
    lines += ["};", "", "static const wchar_t* const kPanelKeys[] = {"]
    lines += [f"    {wide(k)}," for k in plugins.PANEL_KEYS]
    lines += ["};", ""]
    # the mod pack (pack.cpp): Riftstone's own plugins as package.OWN_PLUGINS names them, the licence and the notices
    # the player zip carries, and where the loader's [d3d9] chain points at DXVK (graphics.cpp)
    lines.append("static const wchar_t* const kOwnPlugins[] = {")
    lines += [f"    {wide(k)}," for k in package.OWN_PLUGINS]
    lines += ["};", ""]
    lines.append(f"static const wchar_t* const kLicense = {wide(package._license().decode('utf-8'))};")
    lines.append(f"static const wchar_t* const kDisclaimer = {wide(legal.DISCLAIMER)};")
    lines.append(f"static const wchar_t* const kFree = {wide(legal.FREE)};")
    lines.append(f"static const wchar_t* const kD3d9ChainPath = {wide(loader.D3D9_CHAIN)};")
    lines.append("")
    return "\n".join(lines)


def render_version() -> str:
    """version.h: the version as the code (STUDIO_VERSION_A) and the resource script's version block read it."""
    m = re.match(r"(\d+)\.(\d+)\.(\d+)", __version__)
    if not m:
        raise SystemExit(f"riftstone.__version__ {__version__!r} does not start with three numbers")
    return "\n".join([
        "// Generated by tools/gen_studio_catalog.py from src/riftstone/__init__.py. Never hand-edit.",
        "#pragma once",
        f'#define STUDIO_VERSION_A "{__version__}"',
        f"#define STUDIO_VERSION_N {m.group(1)},{m.group(2)},{m.group(3)},0",
        "",
    ])


def main(argv: list[str]) -> int:
    text = render()
    files = {OUT: text, VERSION: render_version()}
    if "--check" in argv:
        for path, want in files.items():
            have = path.read_text(encoding="ascii") if path.is_file() else ""
            if have.replace("\r\n", "\n") != want:
                print(f"{path.relative_to(ROOT)} is not what tools/gen_studio_catalog.py writes: run it and rebuild the "
                      "exe")
                return 1
        print(f"{OUT.relative_to(ROOT)} and {VERSION.name} match the toolkit's tables ({len(plugins.CATALOG)} features, "
              f"{len(plugins._RULES)} rules) and version {__version__}")
        return 0
    for path, want in files.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(want, encoding="ascii", newline="\n")
        print(f"wrote {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
